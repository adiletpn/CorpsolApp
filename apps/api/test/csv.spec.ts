import { CSV_BOM, buildCsv, csvCell, csvMoney } from '@corpsol/shared';

describe('ячейка CSV', () => {
  it('обычное значение остаётся как есть', () => {
    expect(csvCell('Асель Ким')).toBe('Асель Ким');
  });

  it('точка с запятой внутри значения берётся в кавычки', () => {
    // Иначе адрес «Алматы; Достык 1» разъедется на две колонки.
    expect(csvCell('Алматы; Достык 1')).toBe('"Алматы; Достык 1"');
  });

  it('кавычка внутри значения удваивается', () => {
    expect(csvCell('ТОО "Алатау"')).toBe('"ТОО ""Алатау"""');
  });

  it('перенос строки не разрывает запись', () => {
    expect(csvCell('первая\nвторая')).toBe('"первая\nвторая"');
  });

  it('пустое значение не превращается в слово', () => {
    expect(csvCell(null)).toBe('');
    expect(csvCell(undefined)).toBe('');
  });

  it('ноль остаётся нулём, а не пустотой', () => {
    // Ноль в колонке удержаний — это «удержаний не было»,
    // а пустая ячейка читается как «не посчитали».
    expect(csvCell(0)).toBe('0');
  });
});

describe('защита от подстановки формул', () => {
  it.each(['=', '+', '-', '@'])('значение с «%s» в начале обезврежено', (char) => {
    // Имя приходит из формы, и туда можно вписать формулу нарочно.
    // Открытый бухгалтером файл выполнил бы её без вопросов.
    expect(csvCell(`${char}1+1`)).toBe(`'${char}1+1`);
  });

  it('формула с кавычками обезврежена внутри кавычек ячейки', () => {
    // Значение само по себе требует кавычек, и апостроф должен
    // оказаться внутри них — иначе Excel увидит формулу.
    expect(csvCell('=HYPERLINK("http://зло")')).toBe(
      '"\'=HYPERLINK(""http://зло"")"',
    );
  });

  it('знак внутри значения ничего не ломает', () => {
    expect(csvCell('Иванов-Петров')).toBe('Иванов-Петров');
  });
});

describe('деньги', () => {
  it('тиыны переводятся в тенге с копейками', () => {
    expect(csvMoney(25_000_00)).toBe('25000,00');
  });

  it('дробная часть отделяется запятой, как ждёт Excel', () => {
    expect(csvMoney(1_234_56)).toBe('1234,56');
  });

  it('разряды не разделяются пробелом', () => {
    // Пробел внутри числа Excel принимает за текст,
    // и колонка перестаёт суммироваться.
    expect(csvMoney(1_000_000_00)).not.toContain(' ');
  });

  it('удержание остаётся отрицательным', () => {
    expect(csvMoney(-5_000_00)).toBe('-5000,00');
  });
});

describe('файл целиком', () => {
  it('начинается с метки кодировки', () => {
    // Без неё Excel читает кириллицу в кодировке системы и выдаёт мусор.
    expect(buildCsv(['Имя'], [['Асель']]).startsWith(CSV_BOM)).toBe(true);
  });

  it('строки разделяются по правилам формата', () => {
    const csv = buildCsv(['Имя'], [['Асель'], ['Данияр']]);

    expect(csv).toBe(`${CSV_BOM}Имя\r\nАсель\r\nДанияр\r\n`);
  });

  it('файл без строк всё равно содержит заголовки', () => {
    // Бухгалтер должен увидеть пустой отчёт, а не пустой файл
    // и догадку, что выгрузка сломалась.
    expect(buildCsv(['Имя', 'Оклад'], [])).toBe(`${CSV_BOM}Имя;Оклад\r\n`);
  });
});
